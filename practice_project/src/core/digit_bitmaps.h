// Convert standard 8-bit RGB (0-255) to RGB555 (15-bit color in 16-bit integer)
#define RGB555(r, g, b) (((uint16_t)((r) >> 3) << 10) | \
                         ((uint16_t)((g) >> 3) << 5)  | \
                         ((uint16_t)((b) >> 3)))

// Pre-calculated RGB555 Common Colors
#define COLOR_BLACK   RGB555(0,   0,   0)     // 0x0000
#define COLOR_WHITE   RGB555(255, 255, 255)   // 0x7FFF
#define COLOR_YELLOW  RGB555(255, 255, 0)     // 0x7FE0
#define COLOR_GREEN   RGB555(0,   255, 0)     // 0x03E0
#define COLOR_RED     RGB555(255, 0,   0)     // 0x7C00

